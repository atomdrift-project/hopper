-- hopper's verdict schema: samples, one verdict per scanner, archive contents
-- and references. PostgreSQL 18. See PLAN.md for the design and its evidence.

CREATE TYPE label    AS ENUM ('unknown', 'sighted', 'good', 'bad', 'inconclusive', 'dual-use', 'purgatory');
CREATE TYPE class    AS ENUM ('benign', 'suspicious', 'hostile');
CREATE TYPE outcome  AS ENUM ('ok', 'unsupported', 'timeout', 'error');
CREATE TYPE ref_kind AS ENUM ('dependency', 'command', 'url_fetch');

-- A package URL without its version, or a URL. Stored once.
-- BY DEFAULT so a migration can carry existing ids over.
CREATE TABLE names (
	id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name text NOT NULL UNIQUE CHECK (octet_length(name) <= 2048)
);

-- Foreign keys: a row that references another takes a key lock on it when
-- inserted, and many writers locking one row (a scanner, a popular name)
-- share the lock through a MultiXact, whose churn forces anti-wraparound
-- vacuums of billion-row tables. The keys that would be taken on every scan,
-- enqueue or ingest of a common name are left out where the referenced rows
-- are never deleted (names, samples) or fixed (scanners, held by a CHECK).
-- The rest stay, and verdicts' key on samples is load-bearing: the orphan
-- cleanup in write.go waits on it.

-- What the bytes are, what we believe about them, where they came from.
CREATE TABLE samples (
	id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	sha256       bytea  NOT NULL UNIQUE CHECK (octet_length(sha256) = 32),
	-- NULL until something that read the bytes says: a worker with a size
	-- limit is never handed a file of unknown size.
	size_bytes   bigint,
	file_type    text,
	label        label  NOT NULL DEFAULT 'unknown',
	label_source text,
	created_at   timestamptz NOT NULL DEFAULT now(),
	name_id      bigint, -- names.id; no key, see above
	-- '' is "no version", as in refs, so the two join by plain equality.
	version      text   NOT NULL DEFAULT '',
	published_at timestamptz,
	url          text,
	fetched_at   timestamptz,
	-- Written once. No hot read looks inside it: queues test feed in locations.
	provenance   jsonb COMPRESSION lz4,
	-- Some sighting has named this file, by digest or by release (named()).
	-- Only ever set, by the Go writers after they commit (Store.Cite), and
	-- recomputed whole by Store.Recite: claims are almost never withdrawn,
	-- and a file a withdrawn claim leaves marked costs the one queue that
	-- reads this (second, which checks the ledger again) a wasted row.
	-- Readers that want the exact answer ask named().
	cited        boolean NOT NULL DEFAULT false
);
-- Ends in id so the newest file under a name (a URL fetched again) is the
-- last entry for it.
CREATE INDEX samples_release ON samples (name_id, version, id) WHERE name_id IS NOT NULL;
-- The files of a name newest first, whatever their version: a lookup by name
-- alone, and the sibling rescan after a conviction.
CREATE INDEX samples_name    ON samples (name_id, id) WHERE name_id IS NOT NULL;
-- Triage queues whose population is a predicate on samples alone get their
-- own partial index; samples rows change only when a label, an identity or a
-- citation does, so these cost almost nothing to keep.
-- second: good files a sighting names.
CREATE INDEX samples_cited_good ON samples (id) WHERE label = 'good' AND cited;
-- acquit: bad files whose provenance names no feed (fetched, not reported).
CREATE INDEX samples_acquit ON samples (id)
	WHERE label = 'bad' AND jsonb_typeof(provenance) = 'object' AND NOT provenance ? 'feed';

-- Who can hold an opinion. A scanner with part_of set is a juror: one of the
-- components another scanner weighs to reach its verdict. Jurors are how a
-- verdict was reached and are never cited as a source in their own right.
-- atomscan's verdict is atomdrift's own, whichever process blended it; the
-- drift jurors are isomer's, judging a release against an earlier one.
--
-- A scanner with no part_of other than atomscan is somebody else's: it never
-- feeds atomscan's verdict, and what its opinion counts for is decided when a
-- lookup is answered.
--
-- operator is the body of evidence a scanner speaks for, in the vocabulary
-- sightings.operator already uses, so a scanner's verdict and a sighting
-- relayed from the same scanner count as one voice. NULL means the judgement
-- is ours and never counts as outside corroboration.
CREATE TABLE scanners (
	id       smallint PRIMARY KEY,
	name     text NOT NULL UNIQUE,
	part_of  smallint REFERENCES scanners,
	operator text
);
