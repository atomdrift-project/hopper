-- One scanner's current opinion of one sample. class is the coordinate every
-- scanner shares, and fires_at the level every reader compares: the tightest
-- false-positive budget at which the opinion grades hostile, lower is worse,
-- -1 never fires, NULL unmeasured. The rest of a scanner's own scale
-- (criticality, probability, signature) stays in summary.
--
-- A row is written when the opinion in it changes, and refreshed when a
-- newer scan agrees with it under another ruleset or more than 30 days on,
-- the rule scan uses to trust a stored verdict (store.refreshAge); so ruleset
-- and formed_at say when it was formed or last confirmed, to that grain.
-- When an artifact was last scanned is in scans. A rescan under the same
-- ruleset within the 30 days writes nothing here. A failed scan (outcome other than ok) never
-- replaces an ok row, and no scan replaces an opinion formed after it.
--
-- A member's floor or ml juror that is benign and fires at no level has no
-- row unless the member has been scanned on its own (writer.speaks): 98.7% of
-- the model's rows in the migration rehearsal said only that, about a fifth of
-- the store. A juror with no row has made no statement.
--
-- detail is the scanner's report, zstd-compressed, placement-free and opaque
-- to SQL; digest is the sha256 of it as it was uploaded. Both are NULL when
-- the scanner sent none, and a rescan stores the report again only when the
-- digest differs. atomscan's report is the evidence all of its jurors read,
-- so it rides on atomscan's row. Most are a few dozen bytes (a member's
-- report is its trait molecule) and stay inline; a large one moves to TOAST
-- whole, already compressed, so the row stays narrow. A table of its own was
-- measured at 196 bytes a report with its key, against about 70 here.
-- summary is bounded by the upload's checks (scanresult.MaxSummary), not here:
-- jsonb's stored size is not the size of the text that was checked.
--
-- Fixed-width columns first, widest first, so a row carries no padding.
CREATE TABLE verdicts (
	sample_id  bigint      NOT NULL REFERENCES samples,
	formed_at  timestamptz NOT NULL,
	outcome    outcome     NOT NULL,
	class      class,
	-- scanners.id: a CHECK, not a key (see above). A new scanner widens it.
	scanner_id smallint    NOT NULL CHECK (scanner_id BETWEEN 1 AND 9),
	fires_at   smallint    CHECK (fires_at >= -1),
	ruleset    text        NOT NULL,
	digest     bytea       CHECK (octet_length(digest) = 32),
	summary    jsonb,
	detail     bytea       STORAGE EXTERNAL,
	CHECK ((digest IS NULL) = (detail IS NULL)),
	PRIMARY KEY (sample_id, scanner_id)
);

-- The opinions that are not benign, about 2% of rows: what Raise asks of the
-- files an archive holds, up to 4096 ids at once. Measured at 25,000
-- rehearsal results, the widest archives answer in 0.33 ms with it and 0.98
-- ms (3.2 at worst) through the key, for an index 2% of the key's size.
-- (The triage queues start from scans_flagged.)
CREATE INDEX verdicts_flagged ON verdicts (scanner_id, class, sample_id) WHERE class <> 'benign';

-- What a file says it is: the analyzer's identity block (a version resource,
-- a bundle manifest, a code signature) as the last scan that read the file
-- found it, kept whole in ident. It is a claim, not a fact: an unsigned file
-- can claim any name, and that it does is the signal. name, version and signer
-- are lifted out for the two questions asked of it: what else claims this
-- name, and what else did this signer sign. What a registry says a file is
-- is not here; that is the sample's own name.
CREATE TABLE claims (
	sample_id bigint PRIMARY KEY REFERENCES samples,
	name      text   NOT NULL DEFAULT '',
	version   text   NOT NULL DEFAULT '',
	signer    text   NOT NULL DEFAULT '',
	ident     jsonb  COMPRESSION lz4 NOT NULL
);
-- Indexed by name and by signer when the first reader asks; nothing does yet.

-- What is directly inside an archive, as far as scans have listed it.
-- paths[i] is where child_ids[i] sits in the parent; a file at two paths
-- appears twice. A nested archive has its own row.
--
-- The bytes fix what is inside, but not what a scan lists: an upload names a
-- member only while it has something to say about it, so two archives that
-- hold the same nested archive can list it differently. listed_at is the
-- scan time of the list stored, and only a list from a strictly newer scan
-- replaces it, whichever arrives last; it is the time the list last changed,
-- as a verdict's formed_at is. An empty list is kept only where it replaces
-- one, so that an older list arriving later cannot bring the members back.
--
-- One row per edge was measured at 296 bytes with its indexes against 57
-- here (before listed_at added 8), and production holds about 4.4 billion
-- edges. Each array is its own TOAST value, so walking down reads the ids and never the paths.
CREATE TABLE contents (
	parent_id bigint PRIMARY KEY REFERENCES samples,
	listed_at timestamptz NOT NULL,
	child_ids bigint[] COMPRESSION lz4 NOT NULL,
	paths     text[]   COMPRESSION lz4 NOT NULL,
	CHECK (cardinality(child_ids) = cardinality(paths)),
	CHECK (cardinality(child_ids) BETWEEN 0 AND 100000)
);
-- Which archives hold this file. fastupdate is off so a lookup never has to
-- scan a pending list; inserts measured no slower without it.
CREATE INDEX contents_parents ON contents USING gin (child_ids) WITH (fastupdate = off);

-- The scanned artifact points at that name, whichever file inside it said so.
-- Replaced on every scan of the artifact: a floating ref's version is
-- whatever scan resolved it to at the time.
--
-- version is the exact version the ref is bound to, '' if there is none;
-- requested is the constraint as written, '' when it was already exact, so a
-- non-empty one marks the ref as floating. fetched is, for a url_fetch ref,
-- the sha256 of what the URL served when scanned: a sample row has one name,
-- so bytes first filed under another URL are found by this instead.
CREATE TABLE refs (
	sample_id bigint   NOT NULL REFERENCES samples,
	name_id   bigint   NOT NULL, -- names.id; no key, see above
	version   text     NOT NULL DEFAULT '',
	kind      ref_kind NOT NULL,
	requested text     NOT NULL DEFAULT '',
	fetched   bytea    CHECK (octet_length(fetched) = 32),
	PRIMARY KEY (sample_id, name_id, version, kind)
);
-- Who declares this release.
CREATE INDEX refs_referrers ON refs (name_id, version, sample_id);

-- When each scanned artifact was last scanned, whatever the scan found, and
-- the ruleset and engine of its last scan that reached a verdict: what a
-- lookup reports as the verdict's last confirmation, what the rescan-by-age
-- sweep and triage's freshness read. Every scan of an artifact rewrites its
-- row, so this is the table rescans churn instead of verdicts. Narrow on
-- purpose: the index on scanned_at makes each rewrite a non-HOT update.
-- Members have no row; they are never swept. Each scan leaves a dead row, a
-- little over 1% of the table a day at a 90-day rescan age, so autovacuum is
-- told to come sooner than its default fifth.
--
-- flagged says the scan left something for triage: atomscan, the floor or
-- the model is not benign, or the file is labelled bad. About 2% of scans
-- in production; the triage queues with a time window start from them.
CREATE TABLE scans (
	sample_id  bigint PRIMARY KEY REFERENCES samples,
	scanned_at timestamptz NOT NULL,
	ruleset    text NOT NULL,
	engine     text NOT NULL DEFAULT '',
	flagged    boolean NOT NULL DEFAULT false
) WITH (autovacuum_vacuum_scale_factor = 0.02);
CREATE INDEX scans_age ON scans (scanned_at, sample_id);
CREATE INDEX scans_flagged ON scans (scanned_at, sample_id) WHERE flagged;

-- Files we hold on disk. A path names one file.
CREATE TABLE locations (
	-- Compared as bytes, so a directory is a range of the key (the review
	-- queue reads review/ that way) whatever the database's collation.
	path      text   COLLATE "C" PRIMARY KEY CHECK (octet_length(path) <= 1024),
	sample_id bigint NOT NULL REFERENCES samples,
	source    text,
	feed      text,
	mtime     timestamptz,
	seen_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX locations_sample ON locations (sample_id);

-- Work owed; a row exists only while pending, so the table stays small however
-- large samples grows, and the churn of handing work out lands here.
--
-- priority orders the work (store.Priority; lower first). attempts counts
-- hand-outs; retry_at is when the row may be handed out again: the end of a
-- worker's lease, or of a back-off after an error. NULL means never tried.
-- The work is always a scan: what else a file is owed (an LLM reading, a
-- triage review) is found by the triage queues, not queued here.
CREATE TABLE queue (
	sample_id bigint   PRIMARY KEY, -- samples.id; no key, see above
	priority  smallint NOT NULL,
	queued_at timestamptz NOT NULL DEFAULT now(),
	attempts  smallint NOT NULL DEFAULT 0,
	retry_at  timestamptz,
	note      text
);
-- Never-tried rows first, then the ones whose retry time has come, so rows in
-- flight do not sit at the head of every read. A row handed out 8 times
-- without a result leaves the index: it is stuck, and stays in the table to
-- be seen. Queries spell the 8 out, as the planner needs to match this
-- predicate.
CREATE INDEX queue_next ON queue (priority, retry_at NULLS FIRST, queued_at) WHERE attempts < 8;

-- What outside sources say about a file or a package: the sightings ledger.
-- It is keyed by text, a lowercase sha256 or a package URL without its
-- version, spelled as names are, so it needs no sample_id or name_id and is
-- carried over from the legacy schema as it is, with the acquisition indexes
-- its other readers use. Lookup reads it by subject and folds it with the
-- corroboration ladder. What it names is marked on samples.cited.
--
-- Every reader asks by subject, so the key leads with it and is the only
-- index lookups need; legacy kept a second index on subject beside a key led
-- by source. Asking by source alone (an operator counting or retracting a
-- feed) reads the table, about a million rows.
CREATE TABLE sightings (
	source       text NOT NULL,
	subject      text NOT NULL,
	url          text NOT NULL DEFAULT '',
	note         text NOT NULL DEFAULT '',
	first_seen   timestamptz NOT NULL DEFAULT now(),
	operator     text NOT NULL DEFAULT '',
	-- The releases a package claim names: '' (unsaid), '*', a range, or a
	-- comma-separated list of exact versions. Only a list narrows the claim.
	affected     text NOT NULL DEFAULT '',
	claim        text NOT NULL DEFAULT 'malicious',
	-- How the source arrived at the claim: predicted, hosted or reviewed.
	basis        text NOT NULL DEFAULT 'predicted',
	-- The component that relayed it; never counted as a voice.
	relayer      text NOT NULL DEFAULT '',
	filename     text NOT NULL DEFAULT '',
	handle       text NOT NULL DEFAULT '',
	published_at timestamptz,
	attempted_at timestamptz,
	PRIMARY KEY (subject, source, affected)
);
-- The sighted queues read claims newest first, digests and packages apart.
CREATE INDEX sightings_review_queue ON sightings ((starts_with(subject, 'pkg:')), first_seen DESC)
	INCLUDE (subject, affected) WHERE claim IN ('malicious', 'suspicious');

-- Forager's attempts to fetch what a sighting names, one row per target.
-- Carried over as it is.
CREATE TABLE sighting_acquisitions (
	target       text PRIMARY KEY,
	attempts     integer NOT NULL DEFAULT 0,
	acquired     boolean NOT NULL DEFAULT false,
	last_attempt timestamptz,
	next_attempt timestamptz NOT NULL DEFAULT now(),
	last_error   text NOT NULL DEFAULT '',
	finished_at  timestamptz
);
CREATE INDEX sighting_acquisitions_due ON sighting_acquisitions (next_attempt) WHERE NOT acquired;
CREATE INDEX sighting_acquisitions_unfinished ON sighting_acquisitions (last_attempt) WHERE finished_at IS NULL;

-- exact_versions returns the versions a claim names exactly: a list, or one
-- version written with = or ==. NULL means the claim covers every release:
-- '' (unsaid), '*', and a range, which SQL cannot evaluate (the legacy
-- unnarrowableScope rule). A version holding a range character (a Debian
-- ~rc) reads as a range, and covers every release.
CREATE FUNCTION exact_versions(affected text) RETURNS text[]
	LANGUAGE sql IMMUTABLE PARALLEL SAFE
	RETURN CASE WHEN replace(affected, ' ', '') ~ '^(==?)?[^,<>=^~*|]+(,(==?)?[^,<>=^~*|]+)*$'
		THEN string_to_array(regexp_replace(affected, '[ =]', '', 'g'), ',') END;

-- covers reports whether a claim's affected versions include version.
CREATE FUNCTION covers(affected text, version text) RETURNS boolean
	LANGUAGE sql IMMUTABLE PARALLEL SAFE
	RETURN exact_versions(affected) IS NULL OR version = ANY (exact_versions(affected));

-- named reports whether some sighting names a file, by its digest or by its
-- release. Two index probes.
CREATE FUNCTION named(sha256 bytea, name_id bigint, version text) RETURNS boolean
	LANGUAGE sql STABLE PARALLEL SAFE
	RETURN EXISTS (SELECT 1 FROM sightings g WHERE g.subject = encode(named.sha256, 'hex'))
	    OR EXISTS (SELECT 1 FROM names n JOIN sightings g ON g.subject = n.name
	               WHERE n.id = named.name_id AND covers(g.affected, named.version));

-- sighted_by returns the files a sighting names: by digest, or the files of
-- a release narrowed to the versions the claim covers. Each arm is an index
-- probe by a constant.
CREATE FUNCTION sighted_by(subject text, affected text) RETURNS TABLE (id bigint)
	LANGUAGE sql STABLE
	BEGIN ATOMIC
		SELECT s.id FROM samples s
		WHERE subject ~ '^[0-9a-f]{64}$' AND s.sha256 = decode(subject, 'hex')
		UNION ALL
		SELECT s.id FROM names n JOIN samples s ON s.name_id = n.id
		WHERE subject LIKE 'pkg:%' AND n.name = subject AND covers(affected, s.version);
	END;

-- What a triage worker concluded about a file it was handed, filed under the
-- queue that handed it out (report_type). A queue does not hand a file out
-- again while its report is newer than the file's last scan or younger than
-- the cooldown; some queues never hand it out again. evidence_key ties a
-- gauntlet review to the observation it answered, once.
CREATE TABLE reports (
	id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	sample_id    bigint  NOT NULL REFERENCES samples,
	report_type  text    NOT NULL,
	content      text    NOT NULL,
	provider     text    NOT NULL DEFAULT '',
	duration_ms  integer NOT NULL DEFAULT 0,
	evidence_key text    NOT NULL DEFAULT '',
	created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX reports_sample ON reports (sample_id, report_type, created_at DESC);
CREATE UNIQUE INDEX reports_gauntlet_evidence ON reports (sample_id, evidence_key)
	WHERE report_type = 'gauntlet' AND evidence_key <> '';

-- The most-used packages by name, refreshed from registry download counts;
-- the popular queues order by rank. Carried over as it is: keyed by the name
-- spelled as names spells it.
CREATE TABLE popular_packages (
	purl_base  text PRIMARY KEY,
	ecosystem  text NOT NULL,
	rank       integer NOT NULL,
	source     text NOT NULL,
	updated_at timestamptz NOT NULL DEFAULT now()
);

-- Gauntlet's published scan runs, carried over as they are: keyed by text
-- sha256 because the history outlives the corpus (pruning samples must not
-- erase it). See gauntlet_schema.sql.
CREATE TABLE gauntlet_runs (
	id          text PRIMARY KEY,
	producer    text NOT NULL,
	observed_at text NOT NULL,
	source      text NOT NULL,
	digest      text NOT NULL,
	metadata    text NOT NULL
);
CREATE TABLE gauntlet_samples (
	run_id   text NOT NULL REFERENCES gauntlet_runs (id),
	sha256   text NOT NULL,
	label    text NOT NULL,
	eligible boolean NOT NULL,
	metadata text NOT NULL,
	PRIMARY KEY (run_id, sha256)
);
CREATE INDEX gauntlet_samples_sha ON gauntlet_samples (sha256, run_id);
CREATE TABLE gauntlet_results (
	run_id       text NOT NULL,
	sha256       text NOT NULL,
	scanner      text NOT NULL,
	status       text NOT NULL,
	evidence_key text NOT NULL,
	payload      text NOT NULL,
	PRIMARY KEY (run_id, sha256, scanner),
	FOREIGN KEY (run_id, sha256) REFERENCES gauntlet_samples (run_id, sha256)
);
CREATE INDEX gauntlet_ascan ON gauntlet_results (sha256, run_id)
	WHERE scanner = 'ascan' AND status IN ('benign', 'detected');
CREATE TABLE gauntlet_withdrawals (
	run_id text NOT NULL REFERENCES gauntlet_runs (id),
	sha256 text NOT NULL,
	PRIMARY KEY (run_id, sha256)
);
CREATE INDEX gauntlet_withdrawals_sha ON gauntlet_withdrawals (sha256);

-- Every label change, appended: who moved a file from what to what, and when.
-- Carried over as it is (gauntlet reads it for disputed ground truth;
-- collimator writes it). from_skip and to_skip are the legacy skip states,
-- '' in rows written here.
CREATE TABLE label_events (
	id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	sha256      text NOT NULL,
	from_label  text NOT NULL DEFAULT '',
	to_label    text NOT NULL DEFAULT '',
	from_skip   text NOT NULL DEFAULT '',
	to_skip     text NOT NULL DEFAULT '',
	reason      text NOT NULL,
	observed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX label_events_sha ON label_events (sha256, observed_at);

-- The files one reconcile walk saw on disk, by path. Filled by the walker,
-- read once when the walk completes, and emptied when the next begins: what
-- is in locations and not here is gone, what is here and not there was
-- missed by ingest (a rename the hash cache recognised). UNLOGGED: rebuilt
-- every walk, so durability buys nothing.
CREATE UNLOGGED TABLE walk_staging (
	path   text  COLLATE "C" NOT NULL,
	sha256 bytea NOT NULL
);
CREATE INDEX walk_staging_path ON walk_staging (path);

-- Small facts hopper keeps about itself: reconcile stamps, and where the
-- migration tool has got to. Carried over as it is.
CREATE TABLE hopper_kv (
	key        text PRIMARY KEY,
	value      text NOT NULL,
	updated_at timestamptz NOT NULL DEFAULT now()
);
